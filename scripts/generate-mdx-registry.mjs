import { readdirSync, writeFileSync } from 'node:fs'

// Literal imports let Next split each article into its own compiled chunk.
// Author-owned MDX is compiled at build time, never evaluated from a string.
const files = readdirSync('_posts').filter((name) => name.endsWith('.mdx')).sort()
for (const file of files) {
  if (!/^[a-zA-Z0-9_-]+\.mdx$/.test(file)) throw new Error(`Unsupported post filename: ${file}`)
}
writeFileSync('lib/mdx-posts.generated.ts', `// Generated by scripts/generate-mdx-registry.mjs. Do not edit.\nimport dynamic from 'next/dynamic'\nimport type { ComponentType } from 'react'\nimport type { MDXProps } from 'mdx/types'\n\nexport const mdxPosts: Record<string, ComponentType<MDXProps>> = {\n${files.map((file) => `  ${JSON.stringify(file.slice(0, -4))}: dynamic(() => import('../_posts/${file}')),`).join('\n')}\n}\n`)
